"""Generate quantum-meteor-api/county_centroids.js from a Census county gazetteer.

Usage: python scripts/gen_county_centroids.py <gazetteer.txt> <out.js>

Emits a compact "FIPS,lat,lon;" string. 2 decimals = ~1 km resolution, far
finer than the 320-px map (1 px ~ 10 km).
"""
import sys

src, out = sys.argv[1], sys.argv[2]
rows = []
with open(src, encoding="utf-8") as fh:
    header = fh.readline().split("\t")
    idx = {name.strip(): i for i, name in enumerate(header)}
    gi, li, oi = idx["GEOID"], idx["INTPTLAT"], idx["INTPTLONG"]
    for line in fh:
        parts = line.split("\t")
        if len(parts) <= oi:
            continue
        fips = parts[gi].strip()
        try:
            lat = float(parts[li])
            lon = float(parts[oi])
        except ValueError:
            continue
        rows.append(f"{fips},{lat:.2f},{lon:.2f}")

rows.sort()
blob = ";".join(rows)

with open(out, "w", encoding="utf-8", newline="\n") as fh:
    fh.write(
        "// Generated by scripts/gen_county_centroids.py from the 2023 Census\n"
        "// county gazetteer (internal points). One row per county:\n"
        "//   FIPS,lat,lon;   (5-digit county FIPS, decimal degrees, 2 dp)\n"
        "// Regenerate only when the source table changes; the data is static.\n"
        f"export const COUNTY_CENTROID_BLOB = \"{blob}\";\n"
        "\n"
        "let _index = null;\n"
        "\n"
        "/** FIPS -> [lat, lon]; parses the blob once per Worker isolate. */\n"
        "export function countyCentroid(fips) {\n"
        "  if (!_index) {\n"
        "    _index = new Map();\n"
        "    for (const row of COUNTY_CENTROID_BLOB.split(\";\")) {\n"
        "      const a = row.indexOf(\",\");\n"
        "      const b = row.indexOf(\",\", a + 1);\n"
        "      if (a < 0 || b < 0) continue;\n"
        "      _index.set(row.slice(0, a),\n"
        "                 [+row.slice(a + 1, b), +row.slice(b + 1)]);\n"
        "    }\n"
        "  }\n"
        "  return _index.get(String(fips).padStart(5, \"0\")) || null;\n"
        "}\n"
    )

print(f"{len(rows)} counties, blob {len(blob)} bytes")
